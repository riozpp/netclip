import worker from '../src/index.js';
const env = { ASSETS: { fetch: async () => new Response('') }, PARSE_LIMIT_PER_HOUR: '60' };
const parseRes = await worker.fetch(new Request('http://l/api/parse?url=' + encodeURIComponent('https://v.douyin.com/DJUL3bv7jEA/')), env);
const j = await parseRes.json();
const v = j.data.videos[0];
console.log('target:', v.url.slice(0, 70));
const r = await worker.fetch(new Request('http://l/api/proxy?u=' + encodeURIComponent(v.url) + '&name=' + encodeURIComponent('抖音测试'), { headers: { range: 'bytes=0-2047' } }), env);
console.log('proxy status:', r.status, '| type:', r.headers.get('content-type'), '| len:', r.headers.get('content-length'));
console.log('content-range:', r.headers.get('content-range'));
console.log('disposition:', r.headers.get('content-disposition'));
const buf = new Uint8Array(await r.arrayBuffer());
console.log('bytes:', buf.length, '| magic:', [...buf.slice(4, 12)].map(b => String.fromCharCode(b)).join(''));
