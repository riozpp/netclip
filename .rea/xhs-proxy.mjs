import worker from '../src/index.js';
const env = { ASSETS: { fetch: async () => new Response('') }, PARSE_LIMIT_PER_HOUR: '60' };
const p = await worker.fetch(new Request('http://l/api/parse?url=' + encodeURIComponent('https://xhslink.cn/o/1NEDFxum6cy')), env);
const j = await p.json();
const img = j.data.images[0];
const r = await worker.fetch(new Request('http://l/api/proxy?u=' + encodeURIComponent(img) + '&name=' + encodeURIComponent('小红书图片')), env);
console.log('proxy:', r.status, '| type:', r.headers.get('content-type'), '| len:', r.headers.get('content-length'));
console.log('disp:', r.headers.get('content-disposition'));
const buf = new Uint8Array(await r.arrayBuffer());
console.log('bytes:', buf.length, '| magic:', buf[0].toString(16), buf[1].toString(16));
